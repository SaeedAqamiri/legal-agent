PAGE_RE = re.compile(r"^##\s*صفحه\s*([0-9۰-۹]+)", re.MULTILINE)


def _fa_to_int(value: str) -> int:
    return int(value.translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789")))


def _page_texts(md_dir: Path, doc: str) -> dict[int, str]:
    path = md_dir / f"{doc}.md"
    if not path.is_file():
        raise SystemExit(f"[bench] missing document file: {path}")
    content = path.read_text(encoding="utf-8")
    pages: dict[int, str] = {}
    current = 1
    buffer: list[str] = []
    for line in content.splitlines():
        match = PAGE_RE.match(line)
        if match:
            if buffer:
                pages[current] = "\n".join(buffer)
            current = _fa_to_int(match.group(1))
            buffer = []
        else:
            buffer.append(line)
    if buffer:
        pages[current] = "\n".join(buffer)
    return pages


def resolve_evidence(md_dir: Path, q: Question) -> list[dict]:
    evidence: list[dict] = []
    cache: dict[str, dict[int, str]] = {}
    for doc, phrase in q.evidence_hints:
        if doc not in cache:
            cache[doc] = _page_texts(md_dir, doc)
        pages = sorted(page for page, text in cache[doc].items() if phrase in text)
        if not pages:
            raise SystemExit(
                f"[bench] {q.id}: phrase not found in {doc}: {phrase!r}"
            )
        evidence.append({"doc": doc, "pages": pages, "point": phrase})
    return evidence


